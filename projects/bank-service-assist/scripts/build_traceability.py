"""Build the requirement → story → acceptance → test matrix from repository sources.

Every referenced automated test must exist; `--check` fails when the committed matrix
is stale or a reference cannot be resolved. This proves traceability, not that the
tests passed: CI and the acceptance records hold execution evidence.
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PROJECT = ROOT / "projects/bank-service-assist"
OUTPUT = ROOT / "docs/backlog/traceability-matrix.md"
PY_TEST = re.compile(r"\btest_[a-z0-9_]+\b")
BROWSER_TEST = re.compile(r"\b(?:AUTH-UI|FAIL-UI|(?:UI|CK|SI|NOTE|RP|REF|WF|AG|RACE)-\d+(?:/\d+)*)\b")
AC_ROW = re.compile(r"^\| ([A-Z]+-\d+-AC\d+) \|(.*)\|\s*$")


def test_inventory():
    python, modules = set(), set()
    for path in list(ROOT.glob("services/api/tests/*.py")) + list(ROOT.glob("projects/*/tests/*.py")):
        modules.add(path.stem)
        python.update(re.findall(r"^def (test_[a-z0-9_]+)\(", path.read_text(), re.M))
    browser = set()
    for path in ROOT.glob("apps/web/tests/*.spec.ts"):
        for title in re.findall(r"test\(\s*[`'\"]([^`'\"]+)", path.read_text()):
            browser.update(BROWSER_TEST.findall(title))
    return python, modules, browser


def references(text):
    return sorted(set(PY_TEST.findall(text)) | set(BROWSER_TEST.findall(text)))


def resolved(ref, inventory):
    python, modules, browser = inventory
    return ref in python or ref in modules or ref in browser


def acceptance(story):
    path = PROJECT / "specs" / story / "acceptance.md"
    rows = []
    if path.exists():
        for line in path.read_text().splitlines():
            match = AC_ROW.match(line)
            if match:
                cells = [c.strip() for c in match.group(2).split("|")]
                rows.append((match.group(1), cells[-2], cells[-1]))
    return rows


def build():
    requirements = json.loads((PROJECT / "docs/sprint-01/requirements.json").read_text())
    inventory = test_inventory()
    lines = [
        "# Requirement traceability matrix",
        "",
        "Generated by `projects/bank-service-assist/scripts/build_traceability.py` from the",
        "[requirements registry](../../projects/bank-service-assist/docs/sprint-01/requirements.json)",
        "and each story's acceptance record. A listed test exists in the repository; whether it",
        "passed is shown by CI and the acceptance record. Owner UAT is separate.",
        "",
        "| Requirement | Priority | Stories | Status | Automated tests referenced |",
        "|---|---|---|---|---|",
    ]
    missing = []
    for req in requirements["requirements"]:
        refs = set(req.get("verifiedBy", []))
        for story in req["stories"]:
            for _, evidence, _ in acceptance(story):
                refs.update(references(evidence))
        for ref in refs:
            if not resolved(ref, inventory):
                missing.append((req["id"], ref))
        stories = ", ".join(
            "[{0}](../../projects/bank-service-assist/specs/{0}/acceptance.md)".format(s)
            if (PROJECT / "specs" / s / "acceptance.md").exists()
            else s
            for s in req["stories"]
        )
        tests = ", ".join("`{}`".format(r) for r in sorted(refs)) or "None — manual/UAT evidence only"
        lines.append(
            "| {} | {} | {} | {} | {} |".format(req["id"], req["priority"], stories, req["status"], tests)
        )
    lines += [
        "",
        "Requirements with no automated test are covered by documentation, analytics or",
        "pending UAT/evaluation; they are listed rather than hidden.",
        "",
    ]
    return "\n".join(lines), missing


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text, missing = build()
    if missing:
        for req, ref in missing:
            print("unresolved test reference: {} -> {}".format(req, ref))
        sys.exit(1)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print("traceability matrix is stale; run build_traceability.py")
            sys.exit(1)
        print("PASS: traceability matrix current")
        return
    OUTPUT.write_text(text)
    print("wrote", OUTPUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
